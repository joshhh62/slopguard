"""File discovery and the per-file / per-repo context objects handed to detectors."""

from __future__ import annotations

import ast
import os
import re
import warnings
from collections import Counter
from dataclasses import dataclass, field
from functools import cached_property
from pathlib import Path

from .config import DEFAULT_EXCLUDED_DIRS, Config
from .languages import Language, detect_language

_TEST_PATH = re.compile(r"(^|/)(tests?|__tests__|spec|specs|testing)(/|$)|(^|/)(test_[^/]*|[^/]*_test\.\w+|[^/]*\.(test|spec)\.\w+)$")
_GENERATED = re.compile(
    r"(?i)(?:@generated\b|\bauto-?generated\b|\bcode generated by\b|\bgenerated (?:by|from) (?:the |our )?[\w./ -]{0,40}"
    r"(?:protoc|openapi|swagger|stainless|grpc|codegen|tool|script|compiler)|\bdo not edit\b)"
)
_IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


@dataclass
class FileContext:
    root: Path
    rel: str
    language: Language
    text: str

    @cached_property
    def lines(self) -> list[str]:
        return self.text.splitlines()

    @cached_property
    def is_test(self) -> bool:
        return bool(_TEST_PATH.search(self.rel.lower()))

    @cached_property
    def comments(self) -> dict[int, str]:
        """Map of 1-based line number -> comment text on that line (without the marker)."""
        return _extract_comments(self.lines, self.language)

    @cached_property
    def python_ast(self) -> ast.Module | None:
        """Parsed module for Python files (None for other languages or on syntax errors)."""
        if self.language.name != "python":
            return None
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")  # e.g. invalid escape sequences in scanned code
                return ast.parse(self.text, filename=self.rel)
        except (SyntaxError, ValueError):
            return None

    @cached_property
    def python_nodes(self) -> list[ast.AST]:
        """Every AST node, walked once and shared by all Python rules."""
        return list(ast.walk(self.python_ast)) if self.python_ast is not None else []

    def comment_only(self, lineno: int) -> bool:
        """True when the whole line is a comment (nothing but whitespace before it)."""
        if lineno not in self.comments:
            return False
        stripped = self.lines[lineno - 1].strip()
        return any(stripped.startswith(m) for m in self._comment_markers) or self._in_block(lineno)

    @cached_property
    def _comment_markers(self) -> tuple[str, ...]:
        markers = list(self.language.line_comments)
        if self.language.block_comment:
            markers.append(self.language.block_comment[0])
            markers.append("*")  # continuation lines of /** ... */ blocks
        return tuple(markers)

    def _in_block(self, lineno: int) -> bool:
        return lineno in self._block_lines

    @cached_property
    def _block_lines(self) -> set[int]:
        return _block_comment_lines(self.lines, self.language)

    def line(self, lineno: int) -> str:
        if 1 <= lineno <= len(self.lines):
            return self.lines[lineno - 1]
        return ""


@dataclass
class RepoContext:
    root: Path
    config: Config
    files: list[FileContext] = field(default_factory=list)
    skipped: int = 0
    inventory: list[str] = field(default_factory=list)  # every non-excluded file, scanned or not

    @cached_property
    def identifier_counts(self) -> Counter[str]:
        """How often each identifier appears across the whole repository (for dead-code checks)."""
        counts: Counter[str] = Counter()
        for f in self.files:
            counts.update(_IDENTIFIER.findall(f.text))
        return counts

    @cached_property
    def all_paths(self) -> set[str]:
        return {f.rel for f in self.files}

    def read_text(self, rel: str) -> str | None:
        """Read any file under the root (used for manifests that are not scanned as code)."""
        path = (self.root / rel).resolve()
        if not path.is_file() or self.root.resolve() not in path.parents:
            return None
        try:
            return path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return None

    @cached_property
    def top_level_names(self) -> set[str]:
        try:
            return {p.name for p in self.root.iterdir()}
        except OSError:
            return set()


def discover(root: Path, config: Config) -> RepoContext:
    """Walk ``root`` and load every readable source/config file not excluded by config."""
    repo = RepoContext(root=root, config=config)
    root = root.resolve()
    for dirpath, dirnames, filenames in os.walk(root):
        rel_dir = Path(dirpath).relative_to(root).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        dirnames[:] = sorted(
            d for d in dirnames
            if d not in DEFAULT_EXCLUDED_DIRS
            and not d.endswith(".egg-info")
            and not config.is_excluded(f"{rel_dir}/{d}".lstrip("/") + "/")
        )
        for name in sorted(filenames):
            rel = f"{rel_dir}/{name}".lstrip("/")
            if config.is_excluded(rel):
                continue
            repo.inventory.append(rel)
            language = detect_language(name)
            if language is None:
                continue
            path = Path(dirpath) / name
            try:
                if path.stat().st_size > config.max_file_bytes:
                    repo.skipped += 1
                    continue
                raw = path.read_bytes()
            except OSError:
                repo.skipped += 1
                continue
            if b"\x00" in raw[:4096]:  # binary masquerading as text
                repo.skipped += 1
                continue
            text = raw.decode("utf-8", errors="replace")
            if _GENERATED.search(text[:800]):  # machine-written code is not the author's slop
                repo.skipped += 1
                continue
            repo.files.append(FileContext(root, rel, language, text))
    return repo


def _block_comment_lines(lines: list[str], language: Language) -> set[int]:
    if not language.block_comment:
        return set()
    start, end = language.block_comment
    inside = False
    result: set[int] = set()
    for i, line in enumerate(lines, 1):
        stripped = line.strip()
        if inside:
            result.add(i)
            if end in line:
                inside = False
        elif stripped.startswith(start):
            result.add(i)
            inside = end not in stripped[len(start):]
    return result


def _extract_comments(lines: list[str], language: Language) -> dict[int, str]:
    """Best-effort comment extraction that ignores comment markers inside string literals."""
    comments: dict[int, str] = {}
    block = language.block_comment
    in_block = False
    for i, line in enumerate(lines, 1):
        if in_block:
            end_idx = line.find(block[1]) if block else -1
            comments[i] = line[: end_idx if end_idx != -1 else None].strip().lstrip("*").strip()
            if end_idx != -1:
                in_block = False
            continue
        quote: str | None = None
        j = 0
        while j < len(line):
            ch = line[j]
            if quote:
                if ch == "\\":
                    j += 2
                    continue
                if ch == quote:
                    quote = None
            elif ch in "\"'`":
                quote = ch
            else:
                marker = next((m for m in language.line_comments if line.startswith(m, j)), None)
                if marker:
                    comments[i] = line[j + len(marker):].strip()
                    break
                if block and line.startswith(block[0], j):
                    rest = line[j + len(block[0]):]
                    end_idx = rest.find(block[1])
                    comments[i] = rest[: end_idx if end_idx != -1 else None].strip().lstrip("*").strip()
                    if end_idx == -1:
                        in_block = True
                    break
            j += 1
    return comments
