_EMOJI = {Severity.CRITICAL: "🟥", Severity.HIGH: "🟧", Severity.MEDIUM: "🟨", Severity.LOW: "🟦", Severity.INFO: "⬜"}
_VERDICT_LABEL = {Verdict.CONFIRMED: "AI-confirmed", Verdict.NEEDS_REVIEW: "needs review",
                  Verdict.FALSE_POSITIVE: "AI-dismissed", Verdict.UNTRIAGED: ""}


def _live(result: ScanResult) -> list[Finding]:
    return [f for f in result.findings if f.verdict is not Verdict.FALSE_POSITIVE]


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def to_markdown(result: ScanResult) -> str:
    live = _live(result)
    s = result.stats
    lines = [
        "# SlopGuard report",
        "",
        f"**Health score: {result.score}/100 (grade {result.grade})** · {s.files_scanned} files · "
        f"{s.lines_scanned:,} lines · {', '.join(list(s.languages)[:6])}",
        "",
    ]
    if result.ai_summary:
        lines += ["## AI triage summary", "", result.ai_summary, ""]
    lines += ["## Overview", "", "| Category | " + " | ".join(sev.value.title() for sev in Severity) + " |",
              "|---|" + "---|" * len(Severity)]
    for cat in Category:
        row = [str(sum(1 for f in live if f.category == cat and f.severity == sev)) for sev in Severity]
        lines.append(f"| {cat.label} | " + " | ".join(row) + " |")
    lines.append("")

    for cat in Category:
        items = [f for f in live if f.category == cat]
        if not items:
            continue
        lines += [f"## {cat.label} ({len(items)})", "", "| | Rule | Location | Finding | Fix |", "|---|---|---|---|---|"]
        for f in sorted(items, key=lambda f: (-f.severity.rank, f.path, f.line)):
            verdict = _VERDICT_LABEL[f.verdict]
            detail = f.ai_rationale or f.message
            title = f"**{_md_escape(f.title)}**" + (f" _({verdict})_" if verdict else "")
            lines.append(
                f"| {_EMOJI[f.severity]} {f.severity.value} | `{f.rule_id}` | `{f.location}` | "
                f"{title}<br>{_md_escape(detail)} | {_md_escape(f.fix.splitlines()[0] if f.fix else '')} |"
            )
        lines.append("")

    dismissed = [f for f in result.findings if f.verdict is Verdict.FALSE_POSITIVE]
    if dismissed:
        lines += [f"<details><summary>{len(dismissed)} candidates dismissed by AI triage</summary>", ""]
        lines += [f"- `{f.rule_id}` `{f.location}`: {_md_escape(f.ai_rationale)}" for f in dismissed]
        lines += ["", "</details>", ""]
    if result.ai_usage:
        u = result.ai_usage
        cost = f" · est. ${u['estimated_cost_usd']}" if u.get("estimated_cost_usd") is not None else ""
        lines.append(f"_AI triage: {u['model']} · {u['requests']} requests · {u['tool_calls']} tool calls{cost}_")
    lines.append(f"_Generated by SlopGuard {__version__}_")
    return "\n".join(lines) + "\n"


