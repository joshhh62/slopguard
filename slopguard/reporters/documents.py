def to_html(result: ScanResult) -> str:
    data = {
        "root": result.root, "score": result.score, "grade": result.grade, "stats": vars(result.stats),
        "ai_summary": result.ai_summary, "findings": [f.to_dict() for f in result.findings],
    }
    # Escape "</" so scanned content can never close the <script> block (stored XSS in our own report).
    blob = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    return _HTML.replace("__DATA__", blob).replace("__VERSION__", html.escape(__version__))
